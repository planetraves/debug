import os
import pathlib
import re
import urllib.request

ROOT = pathlib.Path(os.path.expandvars("$PROJECT_ROOT_FOLDER"))
ASSETS = ROOT / "docs" / "assets"

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
    "AppleWebKit/537.36 (KHTML, like Gecko) "
    "Chrome/130.0 Safari/537.36"
)
KEEP_SUBSETS = {"latin", "latin-ext", "fallback"}

GOOGLE_FONTS = {
    "material-symbols-outlined":
        "https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,200,1,0",
    "roboto":
        "https://fonts.googleapis.com/css2?family=Roboto:wght@400;500;600;700;800;900&display=swap",
    "orbitron":
        "https://fonts.googleapis.com/css2?family=Orbitron:wght@400;700;900&display=swap",
    "audiowide":
        "https://fonts.googleapis.com/css2?family=Audiowide&display=swap",
    "monoton":
        "https://fonts.googleapis.com/css2?family=Monoton&display=swap",
    "barlow-semi-condensed":
        "https://fonts.googleapis.com/css2?family=Barlow+Semi+Condensed:"
        "ital,wght@0,100;0,200;0,300;0,400;0,500;0,600;0,700;0,800;0,900;"
        "1,100;1,200;1,300;1,400;1,500;1,600;1,700;1,800;1,900&display=swap",
}

VENDOR = {
    "vendor/supabase-js-2.119.2.js":
        "https://unpkg.com/@supabase/supabase-js@2.119.2/dist/umd/supabase.js",
    "vendor/libphonenumber-min-1.13.3.js":
        "https://unpkg.com/libphonenumber-js@1.13.3/bundle/libphonenumber-min.js",
    "vendor/pico.conditional.slate-2.1.1.min.css":
        "https://unpkg.com/@picocss/pico@2.1.1/css/pico.conditional.slate.min.css",
}

FONT_FACE = re.compile(
    r"(?:/\*\s*([\w-]+)\s*\*/\s*)?@font-face\s*\{(.*?)\}",
    re.S,
)


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def download(url, destination):
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(fetch(url))
    print(f"OK   {destination}")


def localize_font_css(css, slug):
    output = []
    position = 0

    for match in FONT_FACE.finditer(css):
        output.append(css[position:match.start()])
        position = match.end()

        subset = match.group(1) or "fallback"
        if subset not in KEEP_SUBSETS:
            continue

        body = match.group(2)
        url_match = re.search(r"url\((https://[^)]+)\)", body)
        if not url_match:
            continue

        url = url_match.group(1)
        filename = url.rsplit("/", 1)[-1]
        destination = ASSETS / "fonts" / slug / filename
        download(url, destination)

        body = body.replace(url, f"../fonts/{slug}/{filename}")
        if slug == "material-symbols-outlined" and "font-display" not in body:
            body = body.rstrip() + "\n  font-display: block;\n"

        output.append(f"/* {subset} */\n@font-face {{{body}}}\n")

    output.append(css[position:])
    return "".join(output)


def main():
    generated = ["/* Generated by download_assets.py - do not edit */\n"]

    for slug, url in GOOGLE_FONTS.items():
        css = fetch(url).decode("utf-8")
        generated.append(f"\n/* ===== {slug} ===== */\n")
        generated.append(localize_font_css(css, slug))

    fonts_css = ASSETS / "css" / "fonts.css"
    fonts_css.parent.mkdir(parents=True, exist_ok=True)
    fonts_css.write_text("".join(generated), encoding="utf-8")
    print(f"OK   {fonts_css.relative_to(ROOT)}")

    for relative_path, url in VENDOR.items():
        download(url, ASSETS / relative_path)


if __name__ == "__main__":
    main()
