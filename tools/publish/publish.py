#!/usr/bin/env python3
"""Publish real events to the Planet Raves Supabase database (PROD by default).

Events are read from a JSON file that uses the fields of the website's submit form.
Instead of an `image_url`, an event gives an `image_path`: a local image that is
compressed for the web like the website does (resizeImage() in
docs/assets/js/global/eventform.js: 1200 px wide at most, JPEG quality 0.8), uploaded
to the `event-images` storage bucket, and whose public URL is stored in
`events.image_url` when the event is created.

    python tools/publish/publish.py EVENTS.json --creator EMAIL [--dry-run] [--env dev] [--yes]

Works on Windows and macOS. JSON format, secrets to store and options:
tools/publish/README.md
"""
