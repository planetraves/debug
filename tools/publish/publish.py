class EventReader:
    """Read the fields of one JSON event, collecting every error instead of stopping at the first."""

    def __init__(self, raw: dict):
        self.raw = raw
        self.errors: list = []

    def fail(self, key: str, message: str):
        self.errors.append(f"{key}: {message}")

    def get(self, key: str, required: bool = False) -> Any:
        value = self.raw.get(key)
        if isinstance(value, str):
            value = value.strip()
        if value is None or value == "" or value == []:
            if required:
                self.fail(key, "is required")
            return None
        return value

    def text(self, key: str, required: bool = False, max_length: Optional[int] = None) -> Optional[str]:
        value = self.get(key, required)
        if value is None:
            return None
        if not isinstance(value, str):
            self.fail(key, "must be a text")
            return None
        if max_length and len(value) > max_length:
            self.fail(key, f"{len(value)} characters, {max_length} maximum")
        return value

    def whole_number(self, key: str, low: int, high: int) -> Optional[int]:
        value = self.get(key)
        if isinstance(value, str) and value.isdecimal():
            value = int(value)
        if value is None:
            return None
        if isinstance(value, bool) or not isinstance(value, int) or not low <= value <= high:
            self.fail(key, f"must be a whole number from {low} to {high}")
            return None
        return value

    def amount(self, key: str) -> Optional[float]:
        value = self.get(key)
        if isinstance(value, str):
            try:
                value = float(value.replace(",", "."))
            except ValueError:
                pass
        if value is None:
            return None
        if (isinstance(value, bool) or not isinstance(value, (int, float))
                or not math.isfinite(value) or value < 0):
            self.fail(key, "must be a positive amount in euros")
            return None
        return round(float(value), 2)

    def flag(self, key: str) -> bool:
        value = self.get(key)
        if value is None:
            return False
        if not isinstance(value, bool):
            self.fail(key, "must be true or false")
            return False
        return value

    def day(self, key: str, required: bool = False) -> Optional[date]:
        value = self.text(key, required)
        if value is None:
            return None
        try:
            return date.fromisoformat(value)
        except ValueError:
            self.fail(key, f"'{value}' is not a date like 2026-12-31")
            return None

    def email(self, key: str) -> Optional[str]:
        value = self.text(key)
        if value is not None and not EMAIL_RE.fullmatch(value):
            self.fail(key, f"'{value}' is not an email address")
            return None
        return value

    def categories(self) -> list:
        value = self.get("category", required=True)
        if value is None:
            return []
        result = set()
        for item in value if isinstance(value, list) else [value]:
            if isinstance(item, str):
                item = item.strip().lower()
                item = int(item) if item.isdecimal() else CATEGORIES.get(item, item)
            if isinstance(item, bool) or not isinstance(item, int) or item not in CATEGORIES.values():
                self.fail("category", f"unknown category {item!r}: use 0-5 or {', '.join(CATEGORIES)}")
            else:
                result.add(item)
        return sorted(result)

    def tags(self) -> list:
        value = self.get("tags", required=True)
        if value is None:
            return []
        if not isinstance(value, list) or not all(isinstance(tag, str) for tag in value):
            self.fail("tags", 'must be a list of texts, e.g. ["jazz", "concert"]')
            return []
        tags = []
        for tag in value:
            tag = tag.strip().lower()
            if tag and tag not in tags:
                tags.append(tag)
        if TEST_TAG in tags:
            self.fail("tags", f"'{TEST_TAG}' is reserved for test data")
        if not tags:
            self.fail("tags", "at least one tag is required")
        elif len(tags) > MAX_TAGS:
            self.fail("tags", f"{len(tags)} tags, {MAX_TAGS} maximum")
        return tags

    def start_time(self) -> Optional[str]:
        value = self.text("event_start_time")
        if value is None:
            return None
        match = TIME_RE.fullmatch(value)
        if match:
            hours, minutes = int(match.group(1)), int(match.group(2) or 0)
            if hours < 24 and minutes < 60:
                return f"{hours:02d}:{minutes:02d}"
        self.fail("event_start_time", f"'{value}' is not a time like 20:30")
        return None

    def price(self) -> int:
        value = self.get("price")
        if value is None:
            return 0
        if isinstance(value, str):
            value = int(value) if value.isdecimal() else PRICES.get(value.lower(), value)
        if isinstance(value, bool) or not isinstance(value, int) or value not in PRICES.values():
            self.fail("price", "must be 0 (gratuit), 1 (prix libre) or 2 (payant)")
            return 0
        return value

    def phone(self) -> Optional[str]:
        value = self.text("phone")
        if value is None:
            return None
        try:
            number = phonenumbers.parse(value, PHONE_REGION)
        except phonenumbers.NumberParseException:
            number = None
        if number is None or not phonenumbers.is_valid_number(number):
            self.fail("phone", f"'{value}' is not a valid phone number")
            return None
        # same storage format as the website (libphonenumber's number.number)
        return phonenumbers.format_number(number, phonenumbers.PhoneNumberFormat.E164)

    def image(self, base_dir: Path) -> Optional[Path]:
        value = self.text("image_path")
        if value is None:
            return None
        if os.sep == "/":
            value = value.replace("\\", "/")  # path written on Windows
        path = (base_dir / os.path.expandvars(os.path.expanduser(value))).resolve()
        if not path.is_file():
            self.fail("image_path", f"file not found: {path}")
            return None
        return path


def parse_event(raw: Any, number: int, base_dir: Path, today: date,
                default_creator: Optional[str]) -> tuple:
    """Validate one JSON event; return (EventPlan or None, list of errors)."""
    if not isinstance(raw, dict):
        return None, ["must be a JSON object { ... }"]
    r = EventReader(raw)
    for key in raw:
        if not (key.startswith("_") or key in REQUIRED_FIELDS or key in OPTIONAL_FIELDS):
            r.fail(key, f"not allowed: {MANAGED_FIELDS[key]}" if key in MANAGED_FIELDS else "unknown field")

    title = r.text("title", required=True, max_length=MAX_TITLE_LENGTH)

    start, end = r.day("event_date", required=True), r.day("end_date")
    dates = []
    if start:
        n_days = (end - start).days + 1 if end else 1
        if start < today:
            r.fail("event_date", f"{start} is in the past")
        if end and n_days <= 1:
            r.fail("end_date", "must be after event_date")
        elif n_days > MAX_EVENT_DAYS:
            r.fail("end_date", f"an event lasts {MAX_EVENT_DAYS} days at most")
        else:
            dates = [start + timedelta(days=i) for i in range(n_days)]

    code = r.get("location_address_code", required=True)
    if code is not None:
        code = str(code)
        if not POSTAL_CODE_RE.fullmatch(code):
            r.fail("location_address_code", f"'{code}' is not a 5-digit postal code")

    price = r.price()
    min_price, max_price = r.amount("min_price"), r.amount("max_price")
    if price == PAID:
        min_price, max_price = min_price or 0.0, max_price or 0.0
        if min_price > max_price:
            r.fail("min_price", "the reduced price must not exceed max_price")
    else:
        if min_price or max_price:
            r.fail("min_price" if min_price else "max_price", "only allowed when price is 2 (payant)")
        min_price = max_price = None

    min_age, max_age = r.whole_number("min_age", 0, MAX_AGE), r.whole_number("max_age", 0, MAX_AGE)
    if min_age is not None and max_age is not None and min_age > max_age:
        r.fail("max_age", "must be greater than or equal to min_age")

    n_errors = len(r.errors)
    creator = r.email("creator_email") or default_creator
    if not creator and len(r.errors) == n_errors:
        r.fail("creator_email", "missing: add it to the event or pass --creator EMAIL")

    # same format as the website: places in "locations", one "schedule" entry per day
    # (event_date / end_date are computed by the database from the schedule)
    start_time = r.start_time()
    location = {
        "name": r.text("location_name", required=True),
        "address": r.text("location_address", required=True),
        "address_2": r.text("location_address_2"),
        "code": code,
        "town": r.text("location_address_town", required=True),
    }
    payload = {
        "title": title,
        "category": r.categories(),
        "tags": r.tags(),
        "locations": [location],
        "schedule": [{"date": day.isoformat(), "time": start_time, "loc": 0} for day in dates],
        "long_description": r.text("long_description"),
        "price": price,
        "min_price": min_price,
        "max_price": max_price,
        "min_age": min_age,
        "max_age": max_age,
        "phone": r.phone(),
        "email": r.email("email"),
        "site_url": r.text("site_url"),
        "to_eat": r.flag("to_eat"),
        "to_drink": r.flag("to_drink"),
    }
    image = r.image(base_dir)
    if r.errors:
        return None, r.errors
    return EventPlan(number, title, payload, dates, creator, image), []


def load_plans(path: Path, default_creator: Optional[str], allow_duplicates: bool) -> list:
    """Read and validate every event of the JSON file; nothing is published if one is invalid."""
    try:
        with open(path, encoding="utf-8-sig") as f:
            data = json.load(f)
    except OSError as exc:
        raise PublishError(f"cannot read {path}: {exc.strerror or exc}")
    except json.JSONDecodeError as exc:
        raise PublishError(f"{path.name} is not valid JSON: {exc.msg} (line {exc.lineno}, column {exc.colno})")
    if isinstance(data, dict):
        data = [data]
    if not isinstance(data, list) or not data:
        raise PublishError(f"{path.name} must contain a list of events: [ {{...}}, {{...}} ]")

    today = date.today()
    plans, seen, n_invalid = [], {}, 0
    for number, raw in enumerate(data, 1):
        plan, errors = parse_event(raw, number, path.parent, today, default_creator)
        if plan and not allow_duplicates:
            for day in plan.dates:
                first = seen.setdefault((plan.title, day), number)
                if first != number:
                    errors.append(f"same title and date ({day}) as event #{first}")
        if errors:
            n_invalid += 1
            title = raw.get("title") if isinstance(raw, dict) else None
            heading = f"event #{number}" + (f' "{title.strip()}"' if isinstance(title, str) and title.strip() else "")
            error(heading + "\n" + "\n".join(f"     - {e}" for e in errors))
        else:
            plans.append(plan)
    if n_invalid:
        raise PublishError(f"{n_invalid} invalid event(s) in {path.name}: nothing was published")
    return plans


