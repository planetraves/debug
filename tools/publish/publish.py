def load_env_file():
    """Load KEY=VALUE lines from <root>/planetraves.env (variables already set win)."""
    try:
        lines = ENV_FILE.read_text(encoding="utf-8-sig").splitlines()
    except OSError:
        return
    for line in lines:
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            os.environ.setdefault(key.strip(), value.strip())

def keyring_secret(sa: str, username: str) -> str:
    try:
        secret = keyring.get_password(sa, username)
        if not secret:  # Windows: entry saved under another user name
            credential = keyring.get_credential(sa, None)
            secret = credential.password if credential else None
    except KeyringError as exc:
        warn(f"keyring unavailable: {exc}")
        return ""
    return secret or ""


def credentials(env: str) -> tuple[str, str, str, str]:
    name = env.upper()
    url = os.environ.get(f"SUPABASE_{name}_URL", "").strip()
    if not url:
        raise PublishError(f"SUPABASE_{name}_URL is not set (it comes from planetraves.env)")
    api_key = os.environ.get(f"SUPABASE_{name}_ANON_KEY", "").strip()
    if not api_key:
        raise PublishError(f"SUPABASE_{name}_ANON_KEY is not set (it comes from planetraves.env)")
    account_password = keyring_secret(f"planetraves.{env}.sa.password", PLANETRAVES_SERVICE_ACCOUNT_EMAIL)
    if not account_password:
        raise PublishError(
            f"service account credentials for {name} not found. Store them with:\n"
            f"     python -m keyring set planetraves.{env}.sa.password {PLANETRAVES_SERVICE_ACCOUNT_EMAIL}\n"
            "   (see tools/publish/README.md)")
    return url, api_key, PLANETRAVES_SERVICE_ACCOUNT_EMAIL, account_password


def proxy_url() -> Optional[str]:
    """Corporate proxy from PROXY_HOST, skipped when its name does not resolve (outside the office)."""
    host = os.environ.get("PROXY_HOST", "").strip()
    if not host:
        return None
    port = os.environ.get("PROXY_PORT", "").strip() or "8080"
    try:
        socket.getaddrinfo(host, port)
    except OSError:
        info(f"proxy {host} is not reachable from this network: direct connection")
        return None
    info(f"using proxy {host}:{port}")
    user = os.environ.get("PROXY_USER", "").strip()
    if not user:
        return f"http://{host}:{port}"
    password = keyring_secret(host, user)
    return f"http://{quote(user, safe='')}:{quote(password, safe='')}@{host}:{port}"


def tls_verify(proxy: Optional[str]):
    bundle = os.environ.get("SPB_CA_BUNDLE", "").strip()
    if bundle:
        if not os.path.isfile(bundle):
            raise PublishError(f"SPB_CA_BUNDLE: file not found: {bundle}")
        return ssl.create_default_context(cafile=bundle)
    # the corporate proxy intercepts TLS; never skip the verification on a direct connection
    if proxy and os.environ.get("SPB_INSECURE") == "1":
        warn("TLS certificate verification disabled (SPB_INSECURE=1, corporate proxy)")
        return False
    return True


