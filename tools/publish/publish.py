def show_plan(plans: list, profiles: dict, images: dict):
    for plan in plans:
        p = plan.payload
        place = p["locations"][0]
        start_time = p["schedule"][0]["time"]
        when = plan.dates[0].isoformat()
        if len(plan.dates) > 1:
            when += f" -> {plan.dates[-1].isoformat()} ({len(plan.dates)} days)"
        if start_time:
            when += f" at {start_time}"
        creator = profiles[plan.creator]
        print(f"\n{plan.label}")
        info(f"date    : {when}")
        info(f"place   : {place['name']}, {place['town']}")
        info(f"creator : {creator['name']} <{creator['email']}>")
        info(f"image   : {images[plan.image].summary if plan.image else 'none'}")
        if plan.existing_dates:
            warn(f"already published on {', '.join(plan.existing_dates)}: skipped "
                 "(--allow-duplicates to publish it anyway)")


def confirm(action: str, yes: bool) -> bool:
    if yes:
        return True
    try:
        answer = input(f"About to {action}. Continue? (y/N) ")
    except EOFError:
        return False
    return answer.strip().lower() in ("y", "yes", "o", "oui")


def run(args) -> int:
    target = args.env.upper()
    creator = args.creator.strip() if args.creator else None
    if creator and not EMAIL_RE.fullmatch(creator):
        raise PublishError(f"--creator: '{creator}' is not an email address")

    json_path = args.json_file.expanduser().resolve()
    plans = load_plans(json_path, creator, args.allow_duplicates)
    success(f"{len(plans)} valid event(s) in {json_path.name}")
    images = compress_images(plans)

    url, api_key, account_email, account_password = credentials(args.env)
    proxy = proxy_url() if args.proxy else None
    with httpx.Client(proxy=proxy, verify=tls_verify(proxy), timeout=60.0) as http:
        client = supabase.create_client(url, api_key, options=supabase.ClientOptions(httpx_client=http))
        try:
            auth_response = client.auth.sign_in_with_password({
                "email": account_email,
                "password": account_password,
            })
        except Exception as exc:
            raise PublishError(f"service account authentication failed for {target}: {exc}") from exc
        if not auth_response.session:
            raise PublishError(f"service account authentication returned no session for {target}")
        info(f"target  : {target} database ({url})")
        profiles = find_creators(client, plans, target)
        if not args.allow_duplicates:
            for plan in plans:
                plan.existing_dates = existing_dates(client, plan)
        show_plan(plans, profiles, images)

        to_publish = [plan for plan in plans if not plan.existing_dates]
        print()
        if args.dry_run:
            success(f"dry run: {len(to_publish)} event(s) ready for {target}, nothing was sent")
            return 0
        if not to_publish:
            warn("nothing to publish")
            return 0
        if not confirm(f"publish {len(to_publish)} event(s) to {target}", args.yes):
            info("cancelled: nothing was published")
            return 0
        failed = publish(client, to_publish, profiles, images, is_test=args.env == "dev")

    print()
    n_published = len(to_publish) - len(failed)
    if n_published:
        success(f"{n_published} event(s) published to {target}")
    if len(plans) > len(to_publish):
        warn(f"{len(plans) - len(to_publish)} event(s) skipped: already published")
    if failed:
        error(f"{len(failed)} event(s) failed: fix them and run the same command again "
              "(the events already published are skipped)")
        return 1
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Publish real events from a JSON file, with local images (see tools/publish/README.md)")
    parser.add_argument("json_file", type=Path, help="JSON file holding a list of events")
    parser.add_argument("--creator", metavar="EMAIL",
                        help="account the events are published for (events without creator_email)")
    parser.add_argument("--env", choices=("prod", "dev"), default="dev",
                        help="target database (default: prod); dev events are flagged is_test")
    parser.add_argument("--dry-run", action="store_true",
                        help="validate, compress the images and check the database without publishing")
    parser.add_argument("--yes", action="store_true", help="do not ask for confirmation")
    parser.add_argument("--allow-duplicates", action="store_true",
                        help="publish even if an event with the same title exists on the same date")
    parser.add_argument("--proxy", action="store_true", help="connect using PROXY_HOST")
    return parser


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="backslashreplace")  # emojis in titles on non-UTF-8 consoles
    args = build_parser().parse_args()
    load_env_file()
    try:
        return run(args)
    except PublishError as exc:
        error(str(exc))
    except KeyboardInterrupt:
        print()
        error("interrupted")
    except Exception as exc:  # network / API errors: clean message instead of a traceback
        error(f"{type(exc).__name__}: {exc}")
    return 1


if __name__ == "__main__":
    sys.exit(main())
