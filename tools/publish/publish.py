def human_size(n_bytes: int) -> str:
    if n_bytes >= 1_000_000:
        return f"{n_bytes / 1_000_000:.1f} MB"
    return f"{max(1, round(n_bytes / 1000))} KB"


def to_srgb(img: Image.Image) -> Image.Image:
    """Return an sRGB image with transparency flattened on white, as drawn on a browser canvas."""
    has_alpha = img.mode in ("RGBA", "LA", "PA") or "transparency" in img.info
    mode = "RGBA" if has_alpha else "RGB"
    converted = None
    icc_profile = img.info.get("icc_profile")
    if icc_profile and ImageCms:
        try:
            source = img if img.mode in ("RGB", "RGBA", "CMYK", "L") else img.convert(mode)
            converted = ImageCms.profileToProfile(
                source, ImageCms.ImageCmsProfile(io.BytesIO(icc_profile)), SRGB_PROFILE, outputMode=mode)
        except (ImageCms.PyCMSError, OSError, ValueError):
            converted = None  # unusable profile: keep the raw colours
    img = converted if converted is not None else img.convert(mode)
    if has_alpha:
        background = Image.new("RGBA", img.size, (255, 255, 255, 255))
        background.alpha_composite(img)
        img = background.convert("RGB")
    return img


def compress_image(path: Path) -> WebImage:
    """Resize to IMAGE_MAX_WIDTH (never enlarge) and encode as JPEG; metadata (EXIF, GPS) is dropped."""
    with Image.open(path) as source:
        img = ImageOps.exif_transpose(source)  # browsers apply the EXIF orientation too
    before = img.size
    img = to_srgb(img)
    width, height = img.size
    if width > IMAGE_MAX_WIDTH:
        width, height = IMAGE_MAX_WIDTH, max(1, round(height * IMAGE_MAX_WIDTH / width))
        img = img.resize((width, height), RESAMPLE)
    buffer = io.BytesIO()
    img.save(buffer, "JPEG", quality=IMAGE_JPEG_QUALITY, optimize=True, progressive=True)
    data = buffer.getvalue()
    summary = (f"{path.name} {before[0]}x{before[1]} {human_size(path.stat().st_size)}"
               f" -> {width}x{height} JPEG {human_size(len(data))}")
    return WebImage(data, summary)


def compress_images(plans: list) -> dict:
    """Compress every distinct image once, before anything is sent."""
    paths = list(dict.fromkeys(plan.image for plan in plans if plan.image))
    if paths:
        info(f"compressing {len(paths)} image(s)...")
    images, n_failed = {}, 0
    for path in paths:
        try:
            images[path] = compress_image(path)
        except Exception as exc:  # Pillow raises various types for corrupt or unsupported files
            n_failed += 1
            hint = ""
            if path.suffix.lower() in (".heic", ".heif"):
                hint = " (HEIC photo: run `python -m pip install pillow-heif` or export it as JPEG)"
            error(f"cannot read the image {path}: {exc}{hint}")
    if n_failed:
        raise PublishError(f"{n_failed} unreadable image(s): nothing was published")
    return images


